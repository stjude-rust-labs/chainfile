//! A command line tool for generating random test data for chain files.
//!
//! ```shell
//! cargo run --release -p chainfile-generate -- --help
//! ```

use std::fs::File;
use std::io;
use std::io::BufWriter;
use std::io::Write;
use std::path::PathBuf;

use anyhow::Context as _;
use anyhow::Result;
use chainfile_generate::bed;
use chainfile_generate::fixture;
use chainfile_generate::vcf;
use clap::Parser;
use clap::Subcommand;
use rand::SeedableRng as _;
use rand::rngs::StdRng;

/// Generate random test data for chain files.
///
/// Generation is deterministic for a given seed, so any output can be
/// regenerated by passing the same `--seed` (and the same options and inputs).
#[derive(Parser, Debug)]
#[command(name = "chainfile-generate", version, propagate_version = true)]
struct Cli {
    /// The seed for the random number generator.
    ///
    /// When not provided, a random seed is chosen and printed to standard
    /// error.
    #[arg(long, global = true)]
    seed: Option<u64>,

    /// The subcommand to run.
    #[command(subcommand)]
    command: Command,
}

/// The available subcommands.
// NOTE: the help for each subcommand comes from the doc comment on its `Args`
// struct, so the variants are intentionally undocumented (a doc comment on a
// variant would override it).
#[derive(Subcommand, Debug)]
enum Command {
    Fixture(FixtureArgs),

    Bed(BedArgs),

    Vcf(VcfArgs),
}

/// Generate a synthetic reference genome, query genome, and chain file.
///
/// Writes `reference.fa`, `query.fa` (each with a `.fai` index), and
/// `reference-to-query.chain` into the output directory.
///
/// The reference genome is random. The query genome is assembled from copies
/// of reference regions separated by random filler, and the chain file
/// describes exactly how the copies were made. The chains have multiple blocks
/// separated by reference-only, query-only, and double-sided gaps; align to
/// both query strands and to different query contigs; and sometimes overlap
/// on the reference genome (duplications). Some aligned bases are substituted
/// in the query genome, and both genomes have unaligned regions.
///
/// The same seed and options always generate the same files, so pass the seed
/// printed to standard error (or chosen with `--seed`) to regenerate them.
#[derive(clap::Args, Debug)]
struct FixtureArgs {
    /// The directory to write the fixture to (created if it does not exist).
    #[arg(short, long)]
    output_directory: PathBuf,

    /// The fixture options.
    #[command(flatten)]
    options: fixture::Options,
}

/// Generate random BED records for the reference genome of a chain file.
///
/// Writes BED6 records named after the situation each exercises followed by an
/// index (e.g., `spans_gap_12`), sorted by contig name and start. The
/// percentage of records for each situation is set with the options below,
/// and the remaining records are `contained`:
///
/// * `contained`: within a single aligned block of a chain on the positive
///   query strand.
///
/// * `spans_gap`: spans a gap between two aligned blocks of a chain, so it
///   lifts over to multiple segments.
///
/// * `unaligned`: within a reference region that no chain aligns.
///
/// * `multiple_chains`: aligned by two or more chains, either within a
///   reference region that two or more chains align (a duplication) or spanning
///   the junction between blocks of two different chains.
///
/// * `opposite_strand`: within a single aligned block of a chain on the
///   negative query strand.
///
/// Every record is verified to have the intended liftover outcome. The same
/// seed, options, and chain file always generate the same records, so pass the
/// seed printed to standard error (or chosen with `--seed`) to regenerate
/// them.
#[derive(clap::Args, Debug)]
struct BedArgs {
    /// The chain file (optionally gzipped).
    #[arg(short, long)]
    chain: PathBuf,

    /// The BED options.
    #[command(flatten)]
    options: bed::Options,

    /// The output file; standard output is used when not provided.
    #[arg(short, long)]
    output: Option<PathBuf>,
}

/// Generate random VCF records for the reference genome of a chain file.
///
/// Writes VCF records whose IDs are the situation each exercises followed by
/// an index (e.g., `spans_gap_12`), sorted by contig name and position. The
/// percentage of records for each situation is set with the options below,
/// and the remaining records are `contained`:
///
/// * `contained`: a SNV within a single aligned block of a chain on the
///   positive query strand where the query genome matches the reference allele.
///
/// * `spans_gap`: a deletion that spans a gap between two aligned blocks of a
///   chain.
///
/// * `unaligned`: a SNV in a reference region that no chain aligns.
///
/// * `multiple_chains`: a SNV in a reference region that two or more chains
///   align (a duplication) or a padded deletion that spans the junction between
///   blocks of two different chains.
///
/// * `opposite_strand`: like `contained`, but on a chain on the negative query
///   strand.
///
/// * `indel`: a padded insertion or deletion within a single aligned block (on
///   either strand) where the query genome matches the reference allele.
///
/// * `swapped_alleles`: a SNV whose alternate allele (but not reference allele)
///   matches the query genome.
///
/// * `reference_mismatch`: a SNV where neither allele matches the query genome.
///
/// * `multiallelic`: a SNV with two alternate alleles where the query genome
///   matches the reference allele.
///
/// Both FASTA files must be indexed (`.fai`). Every record is verified to have
/// the intended liftover outcome. The same seed, options, and inputs always
/// generate the same records, so pass the seed printed to standard error (or
/// chosen with `--seed`) to regenerate them.
#[derive(clap::Args, Debug)]
struct VcfArgs {
    /// The chain file (optionally gzipped).
    #[arg(short, long)]
    chain: PathBuf,

    /// The reference genome FASTA file.
    #[arg(long)]
    reference_fasta: PathBuf,

    /// The query genome FASTA file.
    #[arg(long)]
    query_fasta: PathBuf,

    /// The VCF options.
    #[command(flatten)]
    options: vcf::Options,

    /// The output file; standard output is used when not provided.
    #[arg(short, long)]
    output: Option<PathBuf>,
}

/// Opens an output for writing.
///
/// [`None`] writes to standard output.
fn open_output(path: Option<&PathBuf>) -> Result<Box<dyn Write>> {
    match path {
        None => Ok(Box::new(BufWriter::new(io::stdout().lock()))),
        Some(path) => File::create(path)
            .map(|file| Box::new(BufWriter::new(file)) as Box<dyn Write>)
            .with_context(|| format!("creating `{}`", path.display())),
    }
}

fn main() -> Result<()> {
    let cli = Cli::parse();

    let seed = cli.seed.unwrap_or_else(|| {
        let seed = rand::random();
        eprintln!("seed: {seed}");
        seed
    });

    let mut rng = StdRng::seed_from_u64(seed);

    match cli.command {
        Command::Fixture(args) => {
            let fixture = fixture::generate(&args.options, &mut rng, &args.output_directory)?;
            eprintln!("chain: {}", fixture.chain.display());
            eprintln!("reference FASTA: {}", fixture.reference_fasta.display());
            eprintln!("query FASTA: {}", fixture.query_fasta.display());
        }
        Command::Bed(args) => {
            let mut writer = open_output(args.output.as_ref())?;
            bed::generate(&args.chain, &args.options, &mut rng, &mut writer)?;
        }
        Command::Vcf(args) => {
            let mut writer = open_output(args.output.as_ref())?;
            vcf::generate(
                &args.chain,
                &args.reference_fasta,
                &args.query_fasta,
                &args.options,
                &mut rng,
                &mut writer,
            )?;
        }
    }

    Ok(())
}
